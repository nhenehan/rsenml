fn work(input: &[u8]) -> usize {
    let mut records = [const { Record::empty() }; 8];
    let mut out = [0u8; 256];
    match senml_cbor::cbor::decode(input, &mut records) {
        Ok(n) => senml_cbor::cbor::encode(&records[..n], &mut out).unwrap_or(0),
        Err(_) => 0,
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    rt::run(INPUT, work)
}
