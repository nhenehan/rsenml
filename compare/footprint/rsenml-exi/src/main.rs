//! rsenml, `exi` feature only: decode (and validate) the bit-packed EXI dump of
//! RFC 8428 section 8, re-encode it. Heap: the bump allocator of `common/bump.rs`.
#![no_std]
#![no_main]

#[path = "../../common/bump.rs"]
mod bump;
#[path = "../../common/rt.rs"]
mod rt;

static INPUT: &[u8] = &[
    0xa0, 0x30, 0x0d, 0x84, 0x80, 0xf3, 0xab, 0x93, 0x71, 0xd3, 0x23, 0x2b, 0xb1, 0xd3, 0x7b, 
    0xb9, 0xd1, 0x89, 0x83, 0x29, 0x91, 0x81, 0xb9, 0x9b, 0x09, 0x81, 0x89, 0x81, 0xc1, 0x81, 
    0x81, 0xb1, 0x99, 0xd2, 0x84, 0xbb, 0x37, 0xb6, 0x3a, 0x30, 0xb3, 0xb2, 0x90, 0x1a, 0xb1, 
    0x58, 0x84, 0xc0, 0x33, 0x04, 0xb1, 0xba, 0xb9, 0x39, 0x32, 0xb7, 0x3a, 0x10, 0x1a, 0x09, 
    0x06, 0x40, 0x38
];

fn work(input: &[u8]) -> usize {
    match rsenml::exi::decode(input).and_then(|pack| rsenml::exi::encode(&pack)) {
        Ok(bytes) => bytes.len(),
        Err(_) => 0,
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    rt::run(INPUT, work)
}
