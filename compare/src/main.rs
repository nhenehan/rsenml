//! Head-to-head comparison of rsenml with the other Rust SenML crates
//! (sindit-senml, senml-cbor, coapum-senml). `cargo run --release` from
//! `compare/` measures everything and writes `../doc/comparison.md`.

mod conformance;
mod env;
mod features;
mod interop;
mod libs;
mod model;
mod perf;
mod rfc;
mod vectors;

use std::fmt::Write as _;

use conformance::Outcome;
use interop::Cell;
use libs::{Fmt, Lib, CBOR_LIBS, JSON_LIBS};

/// Escapes a table cell and keeps it short.
fn cell(s: &str) -> String {
    let mut t: String = s.replace('|', "\\|").replace('\n', " ");
    if t.chars().count() > 110 {
        t = t.chars().take(107).collect::<String>() + "...";
    }
    t
}

fn ns(x: Option<f64>) -> String {
    match x {
        None => "-".into(),
        Some(x) if x >= 1e6 => format!("{:.2} ms", x / 1e6),
        Some(x) if x >= 1e3 => format!("{:.1} µs", x / 1e3),
        Some(x) => format!("{x:.0} ns"),
    }
}

fn outcome_cell(o: &Outcome) -> String {
    match o {
        Outcome::Pass(why) if why.is_empty() => "pass".into(),
        Outcome::Pass(why) => {
            let short: String = why.chars().take(48).collect();
            let more = if why.chars().count() > 48 { "..." } else { "" };
            format!("pass <sub>{}{more}</sub>", cell(&short))
        }
        Outcome::Fail(n) => format!("**FAIL**: {}", cell(n)),
        Outcome::Panic(m) => format!("**PANIC**: {}", cell(m)),
        Outcome::NotApplicable => "n/a".into(),
    }
}

fn main() {
    // Panics inside libraries are caught and reported; keep stderr quiet.
    std::panic::set_hook(Box::new(|_| {}));

    let machine = env::machine();
    let examples = rfc::json_examples();
    assert!(
        !examples.is_empty(),
        "spec/rfc8428.txt not found or not parsed"
    );
    let vectors = vectors::all();

    eprintln!("conformance: {} vectors", vectors.len());
    let rows = conformance::run(&vectors);
    eprintln!("interop");
    let json_matrix = interop::run(Fmt::Json, JSON_LIBS, &examples);
    let cbor_matrix = interop::run(Fmt::Cbor, CBOR_LIBS, &examples);
    let ex_513 = examples
        .iter()
        .find(|e| e.name == "5.1.3")
        .map(|e| e.json.clone())
        .unwrap_or_default();
    let ex_514 = examples
        .iter()
        .find(|e| e.name == "5.1.4")
        .map(|e| e.json.clone())
        .unwrap_or_default();
    let oracle_check = model::diff_res(
        &model::resolve(&model::expected(&ex_514)),
        &model::resolve(&model::expected(&ex_513)),
    );
    let sets = perf::datasets(&ex_513);
    eprintln!("sizes");
    let sizes = perf::sizes(&sets);
    eprintln!("speed");
    let speeds = perf::speeds(&sets);
    eprintln!("dependencies");
    let deps = env::deps();
    eprintln!("footprint (building {} binaries)", env::FOOTPRINT_TARGET);
    let footprints = env::footprints();

    // The RFC section 6 dump against rsenml's own CBOR of the same example.
    let rfc6 = rfc::hex_dumps("6").into_iter().next().unwrap_or_default();
    let ex_512b = examples
        .iter()
        .find(|e| e.name == "5.1.2b")
        .map(|e| e.json.clone())
        .unwrap_or_default();
    let rsenml_512b_cbor = rsenml::json::decode(ex_512b.as_bytes())
        .and_then(|p| rsenml::cbor::encode(&p))
        .unwrap_or_default();
    let rsenml_rfc6_again = rsenml::cbor::decode(&rfc6)
        .and_then(|p| rsenml::cbor::encode(&p))
        .unwrap_or_default();

    let mut md = String::new();
    let w = &mut md;

    // ------------------------------------------------------------ header
    let _ = writeln!(w, "# rsenml compared with other Rust SenML crates\n");
    let _ = writeln!(
        w,
        "Generated by `compare/` (`cargo run --release`); every number and verdict below \
         comes from that run. Do not edit by hand: rerun it.\n"
    );
    let _ = writeln!(w, "## Method\n");
    let _ = writeln!(
        w,
        "- **Libraries run**: rsenml (this repository), sindit-senml 0.3, senml-cbor 0.1, \
         coapum-senml 0.1 (default features: JSON and CBOR), all from crates.io via \
         `compare/Cargo.lock`. Not run, by licence: senml-deser (OLFL-1.3) and erxi (PolyForm \
         Noncommercial); their source review is in `doc/landscape.md`."
    );
    let _ = writeln!(
        w,
        "- **Calls**: rsenml `json::decode`, `cbor::decode`, `cbor::decode_sensml` (validate on \
         decode); sindit-senml `parse_json` (decode, validate, resolve: its only public reader); \
         coapum-senml `SenMLPack::from_json_bytes` then its own `validate()`, and \
         `from_cbor_validated`; senml-cbor `cbor::decode` into a {}-record array. Every call is \
         wrapped in `std::panic::catch_unwind`.",
        libs::SENML_CBOR_CAPACITY
    );
    let _ = writeln!(
        w,
        "- **Oracle**: expected records are written as JSON text and read with serde_json, \
         independently of every library under test; RFC examples are their own oracle (the \
         RFC text). Resolution uses an independent resolver written from sections 4.5-4.6 \
         (`compare/src/model.rs`); as a check, it resolves the 5.1.3 example to exactly the \
         5.1.4 resolved example: **{}**. \"Now\" for relative times is {} for every library.",
        match &oracle_check {
            None => "yes".to_owned(),
            Some(d) => format!("NO ({d})"),
        },
        model::NOW
    );
    let _ = writeln!(
        w,
        "- **Data checks**: for an accepted vector, libraries that expose records as written \
         (rsenml, coapum-senml, senml-cbor) are compared field by field and exactly against the \
         expected records (all 15 labels; a label the library cannot represent counts as \
         missing data). sindit-senml exposes only resolved records, so it is compared against \
         the oracle's resolution, in time order, numbers within 1e-6 + 4 ulp. rsenml is \
         additionally checked the same way through its own `Pack::resolve`. Extension labels \
         are not compared."
    );
    let _ = writeln!(
        w,
        "- **Expectations**: each vector cites its RFC 8428 section. Basis *normative* means a \
         MUST, a table or the section 11 CDDL decides it; *reading* means the RFC is indirect \
         and the expectation is this harness's reading (stated in the description). Vectors: \
         {} JSON, {} CBOR (incl. {} SenSML).",
        vectors.iter().filter(|v| v.fmt == Fmt::Json).count(),
        vectors.iter().filter(|v| v.fmt != Fmt::Json).count(),
        vectors.iter().filter(|v| v.fmt == Fmt::CborSensml).count(),
    );
    let _ = writeln!(
        w,
        "- **Machine**: {} / {}; {}; {}. Timings: median of 51 samples, each a batch of calls \
         lasting at least 200 µs, after warm-up; release profile with `lto = true`, \
         `codegen-units = 1`. One run on a desktop machine: treat differences under ~20% as \
         noise.\n",
        machine.arch, machine.cpu, machine.rustc, machine.cargo
    );

    md.push_str(&features::section(&rows, &deps));
    let w = &mut md;

    // ------------------------------------------------------------ 2. conformance
    let _ = writeln!(w, "## 2. Conformance by vector\n");
    let _ = writeln!(
        w,
        "| Library | Representation | pass | fail | panic | fail (normative vectors only) |\n|---|---|---|---|---|---|"
    );
    let summary_rows: [(Lib, &str, &[Fmt]); 6] = [
        (Lib::Rsenml, "JSON", &[Fmt::Json]),
        (Lib::Sindit, "JSON", &[Fmt::Json]),
        (Lib::Coapum, "JSON", &[Fmt::Json]),
        (Lib::Rsenml, "CBOR", &[Fmt::Cbor, Fmt::CborSensml]),
        (Lib::SenmlCbor, "CBOR", &[Fmt::Cbor, Fmt::CborSensml]),
        (Lib::Coapum, "CBOR", &[Fmt::Cbor, Fmt::CborSensml]),
    ];
    let mut stdout_summary = String::new();
    for (lib, repr, fmts) in summary_rows {
        let (p, f, x) = conformance::tally(&rows, lib, fmts);
        let normative: Vec<_> = rows
            .iter()
            .filter(|r| r.vector.basis == vectors::Basis::Normative)
            .map(|r| conformance::Row {
                vector: r.vector.clone(),
                outcomes: r.outcomes.clone(),
            })
            .collect();
        let (_, nf, _) = conformance::tally(&normative, lib, fmts);
        let _ = writeln!(w, "| {} | {repr} | {p} | {f} | {x} | {nf} |", lib.name());
        let _ = writeln!(
            stdout_summary,
            "  {:<13} {repr:<4}  pass {p:>2}  fail {f:>2}  panic {x}",
            lib.name()
        );
    }
    let _ = writeln!(
        w,
        "\nn/a cells (no API for that input, e.g. SenSML for libraries without a stream reader) \
         are not counted. Some passes on reject vectors are incidental, and the reason in \
         small print shows which: senml-cbor rejects every text map key (\"invalid CBOR \
         input\"), so it also rejects `_` labels and the text key \"v\" without checking them; \
         coapum-senml's CBOR reader rejects every integer map key, i.e. all RFC 8428 CBOR.\n"
    );
    for (title, fmts, libs) in [
        ("JSON vectors", &[Fmt::Json][..], JSON_LIBS),
        ("CBOR vectors", &[Fmt::Cbor, Fmt::CborSensml][..], CBOR_LIBS),
    ] {
        let _ = writeln!(w, "### {title}\n");
        let _ = writeln!(
            w,
            "| id | § | basis | description | expected | {} | {} | {} |\n|---|---|---|---|---|---|---|---|",
            libs[0].name(),
            libs[1].name(),
            libs[2].name()
        );
        for r in rows.iter().filter(|r| fmts.contains(&r.vector.fmt)) {
            let v = &r.vector;
            let expected = match &v.expect {
                vectors::Expect::Accept(recs) => format!("accept ({} rec.)", recs.len()),
                vectors::Expect::Reject => "reject".into(),
            };
            let _ = write!(
                w,
                "| `{}` | {} | {} | {} | {} |",
                v.id,
                v.section,
                match v.basis {
                    vectors::Basis::Normative => "normative",
                    vectors::Basis::Reading => "reading",
                },
                cell(&v.desc),
                expected
            );
            for (_, o) in &r.outcomes {
                let _ = write!(w, " {} |", outcome_cell(o));
            }
            let _ = writeln!(w);
        }
        let _ = writeln!(w);
    }

    // ------------------------------------------------------------ 2. interop
    let _ = writeln!(w, "## 3. Interoperability\n");
    let _ = writeln!(
        w,
        "Each of the {} JSON examples of section 5.1 is read by the encoding library (with its \
         own reader; senml-cbor, which has no JSON reader, is given rsenml's reading), written \
         by it, and read back by every library. A cell counts the examples whose decoded \
         records, resolved, equal the oracle's resolution of the RFC text. Rows: encoder; \
         columns: decoder.\n",
        examples.len()
    );
    for m in [&json_matrix, &cbor_matrix] {
        let fmt = if m.fmt == Fmt::Json { "JSON" } else { "CBOR" };
        let _ = writeln!(
            w,
            "### {fmt}\n\n| encoder \\ decoder | {} | {} | {} |\n|---|---|---|---|",
            m.libs[0].name(),
            m.libs[1].name(),
            m.libs[2].name()
        );
        let _ = writeln!(
            stdout_summary,
            "  interop {fmt} (encoder -> decoders, ok/{}):",
            examples.len()
        );
        for enc in m.libs {
            let _ = write!(w, "| {} |", enc.name());
            let _ = write!(stdout_summary, "    {:<13}", enc.name());
            for dec in m.libs {
                let ok = m
                    .cells
                    .iter()
                    .filter(|(_, e, d, c)| *e == enc && *d == dec && matches!(c, Cell::Ok))
                    .count();
                let _ = write!(w, " {ok}/{} |", examples.len());
                let _ = write!(stdout_summary, " {ok:>2}");
            }
            let _ = writeln!(w);
            let _ = writeln!(stdout_summary);
        }
        let _ = writeln!(w, "\nFirst failure per encoder/decoder pair:\n");
        let mut any = false;
        for enc in m.libs {
            for dec in m.libs {
                if let Some((ex, _, _, c)) = m
                    .cells
                    .iter()
                    .find(|(_, e, d, c)| *e == enc && *d == dec && !matches!(c, Cell::Ok))
                {
                    any = true;
                    let why = match c {
                        Cell::Ok => String::new(),
                        Cell::NoInput(x) => format!("encoder failed: {x}"),
                        Cell::Rejected(x) => format!("rejected: {x}"),
                        Cell::WrongData(x) => format!("wrong data: {x}"),
                        Cell::Panic(x) => format!("PANIC: {x}"),
                    };
                    let _ = writeln!(
                        w,
                        "- {} -> {}, example {ex}: {}",
                        enc.name(),
                        dec.name(),
                        cell(&why)
                    );
                }
            }
        }
        if !any {
            let _ = writeln!(w, "- none");
        }
        let _ = writeln!(w);
    }

    // ------------------------------------------------------------ 3. sizes
    let _ = writeln!(w, "## 4. Encoded sizes\n");
    let _ = writeln!(
        w,
        "Each library encodes the data from its own reading of the JSON. *Faithful* means its \
         own decoder reads the output back to the expected resolved records; a size that is \
         not faithful is for less data. The synthetic pack is 200 records in resolved form \
         (no base fields, absolute times), so every library can carry it. For reference, RFC \
         Table 3 gives 573 (JSON), 649 (XML), 254 (CBOR) and 161 (EXI) bytes for 5.1.3 \
         (the RFC's JSON size includes its whitespace).\n"
    );
    let _ = writeln!(
        w,
        "| library / format | {} (bytes) | faithful | {} (bytes) | faithful | note |\n|---|---|---|---|---|---|",
        sets[0].name, sets[1].name
    );
    let labels: Vec<&str> = perf::codecs().iter().map(|c| c.label).collect();
    for label in &labels {
        let per: Vec<&perf::SizeRow> = sizes.iter().filter(|r| r.codec == *label).collect();
        let _ = write!(w, "| {label} |");
        for set in &sets {
            let Some(r) = per.iter().find(|r| r.dataset == set.name) else {
                let _ = write!(w, " - | - |");
                continue;
            };
            let (s, f) = match (&r.size, &r.faithful) {
                (Err(e), _) => (format!("fails: {}", cell(e)), "-".to_owned()),
                (Ok(n), None) => (n.to_string(), "yes".to_owned()),
                (Ok(n), Some(d)) => (n.to_string(), format!("**no**: {}", cell(d))),
            };
            let _ = write!(w, " {s} | {f} |");
        }
        let note = per.first().map(|r| r.note).unwrap_or("");
        let _ = writeln!(w, " {note} |");
    }
    let _ = writeln!(
        w,
        "\nThe section 6 dump ({} bytes) decoded and re-encoded by rsenml is {}. Encoded from the \
         JSON of the second 5.1.2 example, rsenml writes {} bytes: the dump's last record carries \
         `6: 0` (t = 0), which the JSON example omits.\n",
        rfc6.len(),
        if rsenml_rfc6_again == rfc6 { "byte-identical".to_owned() } else { format!("**different** ({} bytes)", rsenml_rfc6_again.len()) },
        rsenml_512b_cbor.len(),
    );

    // ------------------------------------------------------------ 5. deps
    let _ = writeln!(w, "## 5. Dependencies\n");
    let _ = writeln!(
        w,
        "Unique packages in the normal (non-dev, non-build) dependency tree for the host \
         target, the library itself included: `cargo tree -e normal -p <probe> --prefix none` \
         on a probe crate under `compare/probes/` that depends on that library alone, so \
         features are not unified with the other libraries. *Local* counts path packages \
         (rsenml's own crates and rexi). `no_std` is read from the crate's `src/lib.rs`.\n"
    );
    let _ = writeln!(
        w,
        "| library | probe | packages | of which local | `no_std` |\n|---|---|---|---|---|"
    );
    for d in &deps {
        let total = match &d.total {
            Ok(n) => n.to_string(),
            Err(e) => format!("error: {}", cell(e)),
        };
        let _ = writeln!(w, "| {} | `{}` | {total} | {} | {} |", d.label, d.probe, d.local, d.no_std);
    }
    let _ = writeln!(w);

    // ------------------------------------------------------------ 6. footprint
    let _ = writeln!(w, "## 6. Footprint on {}\n", env::FOOTPRINT_TARGET);
    let _ = writeln!(
        w,
        "Minimal `#![no_std]` `#![no_main]` binaries under `compare/footprint/`, built with \
         `--profile footprint` (`opt-level = \"z\"`, `lto = true`, `codegen-units = 1`, \
         `panic = \"abort\"`) and linked by rust-lld with `_start` as the only root. Each \
         decodes one pack and re-encodes it, with a spinning panic handler. The \
         alloc-needing ones use the 32 KiB bump allocator of `footprint/common/bump.rs` \
         (which shows in `.bss`). Sizes from the ELF section headers, in bytes.\n"
    );
    let _ = writeln!(
        w,
        "| binary | `.text` | `.rodata` | `.data` | `.bss` | `.text` above baseline | what it does |\n|---|---|---|---|---|---|---|"
    );
    let base = footprints
        .first()
        .and_then(|f| f.sections.as_ref().ok())
        .map(|s| s[0]);
    for f in &footprints {
        match &f.sections {
            Ok(s) => {
                let _ = writeln!(
                    w,
                    "| {} | {} | {} | {} | {} | {} | {} |",
                    f.label,
                    s[0],
                    s[1],
                    s[2],
                    s[3],
                    base.map_or("-".into(), |b| (s[0] as i64 - b as i64).to_string()),
                    f.what
                );
                let _ = writeln!(
                    stdout_summary,
                    "  footprint {:<14} .text {:>6}",
                    f.label, s[0]
                );
            }
            Err(e) => {
                let _ = writeln!(
                    w,
                    "| {} | build failed: {} | | | | | {} |",
                    f.label,
                    cell(e),
                    f.what
                );
            }
        }
    }
    let _ = writeln!(
        w,
        "\nsindit-senml and coapum-senml need `std` and are not measured here. The four \
         binaries do not process the same pack in every case (EXI uses the section 8 dump of \
         the first 5.1.2 example; the others the second 5.1.2 example), which does not change \
         which code is linked.\n"
    );

    // ------------------------------------------------------------ 7. timing
    let _ = writeln!(w, "## 7. Timing\n");
    let _ = writeln!(
        w,
        "Median time per call. Each decoder reads its own library's encoding of the data (the \
         outputs of section 4; for coapum-senml these carry less data where section 4 says \
         *not faithful*); each encoder writes from its own in-memory model. What a decode \
         includes differs by library (validation, resolution, allocation); see the note \
         column.\n"
    );
    let _ = writeln!(
        w,
        "| library / format | {0} decode | {0} encode | {1} decode | {1} encode | decode includes |\n|---|---|---|---|---|---|",
        sets[0].name, sets[1].name
    );
    let mut seen: Vec<&str> = Vec::new();
    for r in &speeds {
        if seen.contains(&r.codec) {
            continue;
        }
        seen.push(r.codec);
        let per: Vec<&perf::SpeedRow> = speeds.iter().filter(|x| x.codec == r.codec).collect();
        let get = |set: &str| per.iter().find(|x| x.dataset == set);
        let a = get(sets[0].name);
        let b = get(sets[1].name);
        let _ = writeln!(
            w,
            "| {} | {} | {} | {} | {} | {} |",
            r.codec,
            ns(a.and_then(|x| x.decode_ns)),
            ns(a.and_then(|x| x.encode_ns)),
            ns(b.and_then(|x| x.decode_ns)),
            ns(b.and_then(|x| x.encode_ns)),
            r.note
        );
    }
    let _ = writeln!(w);

    // ------------------------------------------------------------ not measured
    let _ = writeln!(w, "## Not measured\n");
    let _ = writeln!(
        w,
        "- senml-deser and erxi (licences; see `doc/landscape.md`).\n\
         - XML and EXI against other libraries: no other Rust crate implements them \
         (coapum-senml's `xml` feature is a stub, per `doc/landscape.md`).\n\
         - Heap allocations per call, and peak memory: not instrumented.\n\
         - Robustness beyond these vectors (fuzzing).\n\
         - Footprint of sindit-senml and coapum-senml (`std` only), and of rsenml `xml`."
    );

    let path = rfc::root().join("doc/comparison.md");
    match std::fs::write(&path, &md) {
        Ok(()) => println!("wrote {}", path.display()),
        Err(e) => eprintln!("cannot write {}: {e}", path.display()),
    }
    println!(
        "machine: {} / {} / {}\nconformance (vectors: {}):\n{stdout_summary}",
        machine.arch,
        machine.cpu,
        machine.rustc,
        vectors.len()
    );
}
